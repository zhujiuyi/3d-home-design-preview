function expectWallDraw(f, start, end, expected, modifiers) {
  f.event('pointerdown', ...start, undefined, modifiers);
  f.event('pointermove', ...end, undefined, modifiers);
  assert.deepEqual(array(f.editor.inspect().drag.preview), expected, 'live preview geometry');
  f.event('pointerup', ...end, undefined, modifiers);
  assert.deepEqual(array(f.ctx.state.floorplan.walls.at(-1).slice(0,4)), expected, 'committed geometry matches preview');
}

